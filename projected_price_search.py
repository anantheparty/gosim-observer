#!/usr/bin/env python3
"""Direct integer-cent capacity-price search for the audited k=8 bound.

Every evaluated objective is a valid *all-17-awarded conditional* upper bound.
The final certificate is generated by the existing full-arc audit and the
unconditional 2^17 request-subset enumerator; this search itself is only a
heuristic way to find better nonnegative Lagrange prices.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import time
from pathlib import Path

import numpy as np
from numba import njit
from scipy.optimize import linprog

import bounds_practice_projection as projection
from bounds_request_conditioned import PRACTICE, request_branches


KEYS = (
    "T00018", "T00029", "T00030", "T00031",
    "T00024", "T00021", "T00040", "T00015",
)
NEG_INF = -(10**15)


@njit(cache=True)
def _popcount(mask: int) -> int:
    result = 0
    while mask:
        mask &= mask - 1
        result += 1
    return result


@njit(cache=True)
def _dp_with_trace(
    n, complete_ptr, complete_end, complete_tile, reduced,
    complete_tagged, partial_ptr, partial_end, actionable_mask,
    key_index, required_key_mask, mandatory_key_mask,
    key_deadline_unit, earliest_terminal_unit, theta, k,
):
    """Exact conditional projection and one maximizing set of K first arcs."""
    states = 1 << k
    dp = np.full((n + 1, states), NEG_INF, np.int64)
    terminal = np.full(states, NEG_INF, np.int64)
    for mask in range(states):
        if mandatory_key_mask & (~mask):
            continue
        terminal[mask] = -projection.REQUIRED_MISS_CENTS * _popcount(
            required_key_mask & (~mask)
        )
        dp[n, mask] = terminal[mask]

    for u in range(n - 1, -1, -1):
        boundary = ((u // projection.POINTS_PER_SLOT) + 1) * projection.POINTS_PER_SLOT
        for mask in range(states):
            best = terminal[mask] if u >= earliest_terminal_unit else NEG_INF
            wait_cost = (
                projection.WAIT_UNIT_CENTS * (boundary - u)
                if actionable_mask[u] & (~mask) else 0
            )
            future = dp[boundary, mask]
            if future > NEG_INF // 2:
                candidate = future - wait_cost
                if candidate > best:
                    best = candidate
            for j in range(partial_ptr[u], partial_ptr[u + 1]):
                candidate = dp[partial_end[j], mask]
                if candidate > best:
                    best = candidate
            for j in range(complete_ptr[u], complete_ptr[u + 1]):
                tile = complete_tile[j]
                bit_index = key_index[tile]
                if bit_index >= 0:
                    bit = 1 << bit_index
                    if not (mask & bit):
                        if u >= key_deadline_unit[bit_index]:
                            continue
                        future = dp[complete_end[j], mask | bit]
                        if future <= NEG_INF // 2:
                            continue
                        candidate = future + reduced[j]
                    elif complete_tagged[j]:
                        candidate = dp[complete_end[j], mask]
                    else:
                        continue
                else:
                    future = dp[complete_end[j], mask]
                    if future <= NEG_INF // 2:
                        continue
                    candidate = future - (0 if complete_tagged[j] else theta[tile])
                if candidate > best:
                    best = candidate
            dp[u, mask] = best

    chosen = np.full(k, -1, np.int32)
    u = 0
    mask = 0
    while u < n:
        value = dp[u, mask]
        if u >= earliest_terminal_unit and value == terminal[mask]:
            break
        boundary = ((u // projection.POINTS_PER_SLOT) + 1) * projection.POINTS_PER_SLOT
        wait_cost = (
            projection.WAIT_UNIT_CENTS * (boundary - u)
            if actionable_mask[u] & (~mask) else 0
        )
        if dp[boundary, mask] > NEG_INF // 2 and dp[boundary, mask] - wait_cost == value:
            u = boundary
            continue
        moved = False
        for j in range(partial_ptr[u], partial_ptr[u + 1]):
            if dp[partial_end[j], mask] == value:
                u = partial_end[j]
                moved = True
                break
        if moved:
            continue
        for j in range(complete_ptr[u], complete_ptr[u + 1]):
            tile = complete_tile[j]
            bit_index = key_index[tile]
            if bit_index >= 0:
                bit = 1 << bit_index
                if not (mask & bit):
                    if u >= key_deadline_unit[bit_index]:
                        continue
                    future = dp[complete_end[j], mask | bit]
                    if future <= NEG_INF // 2:
                        continue
                    candidate = future + reduced[j]
                    next_mask = mask | bit
                elif complete_tagged[j]:
                    candidate = dp[complete_end[j], mask]
                    next_mask = mask
                else:
                    continue
            else:
                future = dp[complete_end[j], mask]
                if future <= NEG_INF // 2:
                    continue
                candidate = future - (0 if complete_tagged[j] else theta[tile])
                next_mask = mask
            if candidate == value:
                if bit_index >= 0 and next_mask != mask:
                    chosen[bit_index] = j
                u = complete_end[j]
                mask = next_mask
                moved = True
                break
        if not moved:
            raise AssertionError("DP trace failed to find maximizing transition")
    return int(dp[0, 0]), chosen


class PriceProblem:
    def __init__(self, original_prices: Path, theta_cents: int):
        self.data = projection.build_data(PRACTICE, original_prices, False)
        self.n = self.data["n"]
        self.tile_ids = self.data["tile_ids"]
        self.key_index = np.full(len(self.tile_ids), -1, np.int8)
        for b, tile in enumerate(KEYS):
            self.key_index[self.tile_ids.index(tile)] = b
        # calculate() fills the scorer-exact actionability cache.
        projection.calculate(self.data, list(KEYS), theta_cents)
        self.actionable_mask = np.zeros(self.n, np.uint8)
        for b, tile in enumerate(KEYS):
            self.actionable_mask[self.data["actionable_cache"][tile]] |= 1 << b
        self.required_key_mask = sum(
            1 << b for b, tile in enumerate(KEYS)
            if self.data["scorer"].tiles[tile].scheduling_class == "REQUIRED"
        )
        self.original_prices = self.data["prices"].copy()
        self.starts = np.repeat(
            np.arange(self.n, dtype=np.int32),
            np.diff(self.data["complete_ptr"]),
        )
        self.ends = self.data["complete_end"]
        self.tiles = self.data["complete_tile"]
        prefix = np.empty(self.n + 1, np.int64)
        prefix[0] = 0
        np.cumsum(self.original_prices, out=prefix[1:])
        self.q = self.data["complete_reduced"] + prefix[self.ends] - prefix[self.starts]
        self.by_tile = [np.flatnonzero(self.tiles == i) for i in range(len(self.tile_ids))]
        scorer = self.data["scorer"]
        requests = request_branches(scorer, self.data["impossible_requests"])
        assert len(requests) == 17 and self.data["request_cents"] == 392000
        instants = np.array([
            slot.timestamp_utc.timestamp() + offset * 150
            for slot in scorer.slots for offset in range(6)
        ], np.float64)
        self.instants = instants
        self.earliest_terminal = int(np.searchsorted(
            instants, max(r.available_from_utc.timestamp() for r, _ in requests),
            side="left",
        ))
        self.branch_deadlines = []
        self.branch_key_masks = []
        self.branch_key_deadlines = []
        for selected in itertools.product(*(options for _, options in requests)):
            deadlines = np.full(len(self.tile_ids), self.n, np.int32)
            for (request, _), required_tiles in zip(requests, selected):
                d = int(np.searchsorted(instants, request.deadline_utc.timestamp(), side="left"))
                for tile_id in required_tiles:
                    i = self.tile_ids.index(tile_id)
                    deadlines[i] = min(int(deadlines[i]), d)
            key_deadlines = np.full(len(KEYS), self.n, np.int32)
            key_mask = 0
            for b, tile in enumerate(KEYS):
                d = int(deadlines[self.tile_ids.index(tile)])
                if d < self.n:
                    key_mask |= 1 << b
                    key_deadlines[b] = d
            self.branch_deadlines.append(deadlines)
            self.branch_key_masks.append(key_mask)
            self.branch_key_deadlines.append(key_deadlines)
        assert len(self.branch_deadlines) == 2
        assert self.branch_key_masks[0] == self.branch_key_masks[1]
        assert np.array_equal(self.branch_key_deadlines[0], self.branch_key_deadlines[1])
        self.external_indices = []
        for deadlines in self.branch_deadlines:
            lists = []
            for i in range(len(self.tile_ids)):
                if self.key_index[i] >= 0:
                    lists.append(np.empty(0, np.int32))
                    continue
                indices = self.by_tile[i]
                if deadlines[i] < self.n:
                    indices = indices[self.starts[indices] < deadlines[i]]
                lists.append(indices)
            self.external_indices.append(lists)

    def evaluate(self, prices: np.ndarray, theta_cents: int, trace: bool = False):
        if prices.shape != (self.n,) or np.any(prices < 0):
            raise ValueError("prices must be nonnegative on each time unit")
        prefix = np.empty(self.n + 1, np.int64)
        prefix[0] = 0
        np.cumsum(prices, out=prefix[1:])
        reduced = self.q - prefix[self.ends] + prefix[self.starts]
        theta = np.full(len(self.tile_ids), theta_cents, np.int64)
        theta[self.key_index >= 0] = 0
        dp, key_arcs = _dp_with_trace(
            self.n, self.data["complete_ptr"], self.ends, self.tiles,
            reduced, self.data["complete_tagged"], self.data["partial_ptr"],
            self.data["partial_end"], self.actionable_mask, self.key_index,
            self.required_key_mask, self.branch_key_masks[0],
            self.branch_key_deadlines[0], self.earliest_terminal, theta, len(KEYS),
        )
        if dp <= NEG_INF // 2:
            raise AssertionError("conditional DP unexpectedly infeasible")
        constant = int(prices.sum() + self.data["request_cents"] + theta.sum() + dp)
        branch_values = []
        branch_arcs = []
        for b, deadlines in enumerate(self.branch_deadlines):
            external = 0
            chosen = []
            for i in range(len(self.tile_ids)):
                if self.key_index[i] >= 0:
                    continue
                indices = self.external_indices[b][i]
                if len(indices) == 0:
                    if deadlines[i] < self.n:
                        external = NEG_INF
                        break
                    continue
                selected = int(indices[np.argmax(reduced[indices])])
                value = int(reduced[selected])
                if deadlines[i] < self.n or value > 0:
                    external += value
                    chosen.append(selected)
            branch_values.append(constant + external)
            branch_arcs.append(chosen)
        winning = int(np.argmax(np.asarray(branch_values)))
        result = {
            "objective_cents": int(branch_values[winning]),
            "branch_cents": [int(v) for v in branch_values],
            "winning_branch": winning,
            "dp_cents": int(dp),
            "theta_cents": int(theta_cents),
            "nonzero_price_cells": int(np.count_nonzero(prices)),
        }
        if trace:
            diff = np.zeros(self.n + 1, np.int16)
            selected_arcs = branch_arcs[winning] + [int(j) for j in key_arcs if j >= 0]
            for j in selected_arcs:
                diff[self.starts[j]] += 1
                diff[self.ends[j]] -= 1
            occupancy = np.cumsum(diff[:-1], dtype=np.int16)
            result["subgradient"] = 1 - occupancy.astype(np.int16)
            result["selected_arc_count"] = len(selected_arcs)
            result["max_relaxed_occupancy"] = int(occupancy.max())
            result["overlap_cells"] = int(np.count_nonzero(occupancy > 1))
            result["unused_priced_cells"] = int(np.count_nonzero((prices > 0) & (occupancy == 0)))
            result["selected_key_arcs"] = [int(j) for j in key_arcs if j >= 0]
            result["selected_external_arcs"] = branch_arcs[winning]
        return result

    def arc_choice_summary(self, result: dict, prices: np.ndarray) -> dict:
        prefix = np.empty(self.n + 1, np.int64)
        prefix[0] = 0
        np.cumsum(prices, out=prefix[1:])

        def describe(j: int) -> dict:
            u, v = int(self.starts[j]), int(self.ends[j])
            return {
                "tile_id": self.tile_ids[int(self.tiles[j])],
                "start_unit": u, "end_unit": v,
                "start_epoch": float(self.instants[u]),
                "science_upper_cents": int(self.q[j]),
                "capacity_price_cents": int(prefix[v] - prefix[u]),
                "reduced_cents": int(self.q[j] - (prefix[v] - prefix[u])),
            }

        return {
            "winning_rq0004_branch": result["winning_branch"],
            "key_first_arcs": [describe(j) for j in result["selected_key_arcs"]],
            "nonkey_first_arcs": [describe(j) for j in result["selected_external_arcs"]],
        }


def _save_prices(path: Path, prices: np.ndarray) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(path, prices_cents=prices.astype(np.int64))
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _bundle_search(problem: PriceProblem, initial: np.ndarray, theta: int,
                   radii: list[int], iterations_per_radius: int,
                   start: float, seconds: float, verbose: bool,
                   prox: float):
    """Kelley cutting planes in a sparse, bounded price neighborhood.

    Every cut is a true supporting plane of the convex conditional bound.
    The restricted master is solely a price *proposal* mechanism: only oracle
    evaluations of the proposed integer-cent price are used as score bounds.
    """
    best_price = initial.copy()
    best = problem.evaluate(best_price, theta, trace=True)
    cuts = [(best["objective_cents"], best_price.copy(), best["subgradient"].copy())]
    seen = {best_price.tobytes()}
    history = []
    for radius in radii:
        center = best_price.copy()
        for local_it in range(iterations_per_radius):
            if seconds and time.monotonic() - start >= seconds:
                return best, best_price, history
            active = center > 0
            for _, _, g in cuts:
                active |= g < 0
            active_ix = np.flatnonzero(active)
            # Stored supporting planes are evaluated only on these variables;
            # all other λ coordinates remain fixed at the current center.
            rows = []
            rhs = []
            m = len(active_ix)
            for value, point, g in cuts:
                gg = g[active_ix].astype(np.float64)
                rows.append(np.r_[gg, -1.0, np.zeros(m, np.float64)])
                intercept = value + int(np.dot(g[~active], center[~active] - point[~active]))
                rhs.append(float(np.dot(gg, point[active_ix])) - intercept)
            if prox:
                for col, i in enumerate(active_ix):
                    row = np.zeros(2 * m + 1, np.float64)
                    row[col] = 1.0
                    row[m + 1 + col] = -1.0
                    rows.append(row)
                    rhs.append(float(center[i]))
                    row = np.zeros(2 * m + 1, np.float64)
                    row[col] = -1.0
                    row[m + 1 + col] = -1.0
                    rows.append(row)
                    rhs.append(float(-center[i]))
            c = np.zeros(2 * m + 1, np.float64)
            c[m] = 1.0
            c[m + 1:] = prox
            bounds = [
                (float(max(0, int(center[i]) - radius)), float(int(center[i]) + radius))
                for i in active_ix
            ] + [(None, None)] + [(0.0, None)] * m
            solved = linprog(c, A_ub=np.asarray(rows), b_ub=np.asarray(rhs),
                             bounds=bounds, method="highs")
            if not solved.success:
                raise RuntimeError(f"bundle master failed: {solved.message}")
            candidate = center.copy()
            candidate[active_ix] = np.rint(solved.x[:m]).astype(np.int64)
            if candidate.tobytes() in seen:
                break
            seen.add(candidate.tobytes())
            evaluated = problem.evaluate(candidate, theta, trace=True)
            cuts.append((evaluated["objective_cents"], candidate.copy(),
                         evaluated["subgradient"].copy()))
            improved = evaluated["objective_cents"] < best["objective_cents"]
            if improved:
                best, best_price = evaluated, candidate.copy()
            row = {
                "radius_cents": radius,
                "local_iteration": local_it + 1,
                "active_price_cells": len(active_ix),
                "cuts": len(cuts),
                "master_stabilized_objective": round(float(solved.fun), 3),
                "candidate_cents": int(evaluated["objective_cents"]),
                "best_cents": int(best["objective_cents"]),
                "improved": bool(improved),
                "elapsed_seconds": round(time.monotonic() - start, 2),
            }
            history.append(row)
            if verbose or improved or (local_it + 1) % 10 == 0:
                print(json.dumps({"bundle": row}), flush=True)
    return best, best_price, history


def run(args):
    start = time.monotonic()
    problem = PriceProblem(args.prices, args.theta)
    prices = problem.original_prices.copy()
    baseline = problem.evaluate(prices, args.theta, trace=True)
    if baseline["objective_cents"] != 2179670:
        raise AssertionError(f"published conditional bound changed: {baseline['objective_cents']}")
    best = (int(baseline["objective_cents"]), prices.copy(), args.theta)
    current = baseline
    history = []
    theta_candidates = sorted(set(range(max(0, args.theta - 40), args.theta + 41, 5)) | {args.theta})
    for theta in theta_candidates:
        candidate = problem.evaluate(prices, theta)
        if candidate["objective_cents"] < best[0]:
            best = (candidate["objective_cents"], prices.copy(), theta)
    prices = best[1].copy()
    current = problem.evaluate(prices, best[2], trace=True)
    bundle_history = []
    if args.bundle_iterations:
        candidate, candidate_prices, bundle_history = _bundle_search(
            problem, prices, best[2],
            [int(x) for x in args.bundle_radii.split(",") if x],
            args.bundle_iterations, start, args.seconds, args.verbose,
            args.bundle_prox,
        )
        if candidate["objective_cents"] < best[0]:
            best = (candidate["objective_cents"], candidate_prices.copy(), best[2])
            prices = candidate_prices.copy()
            current = candidate
    stagnation = 0
    for it in range(args.iterations):
        g = current["subgradient"].astype(np.int64)
        active = (g < 0) | (prices > 0)
        g[~active] = 0
        norm2 = int(np.dot(g, g))
        if norm2 == 0:
            break
        gap = max(1, current["objective_cents"] - args.lower_bound_cents)
        polyak = max(1, min(200, int(gap / norm2)))
        steps = sorted(set((1, 2, 5, 10, 20, 40, 80, 160, polyak, max(1, polyak // 2))))
        trials = []
        for step in steps:
            trial = np.maximum(prices - step * g, 0)
            if np.array_equal(trial, prices):
                continue
            candidate = problem.evaluate(trial, best[2])
            trials.append((candidate["objective_cents"], step, trial))
        if not trials:
            break
        trials.sort(key=lambda row: row[0])
        score, step, trial = trials[0]
        accepted = score < current["objective_cents"]
        if accepted:
            prices = trial
            current = problem.evaluate(prices, best[2], trace=True)
            stagnation = 0
        else:
            stagnation += 1
        if score < best[0]:
            best = (score, trial.copy(), best[2])
        if (it + 1) % args.theta_scan_every == 0 or (stagnation >= 3 and it + 1 < args.iterations):
            for theta in theta_candidates:
                candidate = problem.evaluate(prices, theta)
                if candidate["objective_cents"] < best[0]:
                    best = (candidate["objective_cents"], prices.copy(), theta)
            if best[2] != current["theta_cents"] and np.array_equal(prices, best[1]):
                current = problem.evaluate(prices, best[2], trace=True)
                stagnation = 0
        row = {
            "iteration": it + 1, "current_cents": int(current["objective_cents"]),
            "best_cents": int(best[0]), "step_cents": int(step),
            "accepted": bool(accepted), "overlap_cells": current["overlap_cells"],
            "nonzero_price_cells": current["nonzero_price_cells"],
            "elapsed_seconds": round(time.monotonic() - start, 2),
        }
        history.append(row)
        if args.verbose or it == 0 or (it + 1) % 10 == 0 or best[0] == score:
            print(json.dumps(row), flush=True)
        if stagnation >= args.stagnation_limit:
            break
        if args.seconds and time.monotonic() - start >= args.seconds:
            break

    output = args.out
    output.mkdir(parents=True, exist_ok=True)
    price_file = output / "best_prices.npz"
    price_sha = _save_prices(price_file, best[1])
    final = problem.evaluate(best[1], best[2], trace=True)
    payload = {
        "scope": "dev-reference; conditional on all 17 earnable requests",
        "method": "integer-cent projected subgradient and stabilized sparse bundle with exact DP oracle",
        "keys": list(KEYS), "baseline_cents": baseline["objective_cents"],
        "baseline_theta_cents": args.theta, "best_cents": int(best[0]),
        "best_theta_cents": int(best[2]), "price_file": str(price_file),
        "price_sha256": price_sha, "best_branch_cents": final["branch_cents"],
        "nonzero_price_cells": final["nonzero_price_cells"],
        "overlap_cells": final["overlap_cells"],
        "iterations": len(history), "history": history,
        "bundle_history": bundle_history,
        "elapsed_seconds": round(time.monotonic() - start, 2),
    }
    (output / "search_summary.json").write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    (output / "relaxed_arc_choices.json").write_text(
        json.dumps({
            "baseline": problem.arc_choice_summary(baseline, problem.original_prices),
            "best": problem.arc_choice_summary(final, best[1]),
        }, indent=2, sort_keys=True) + "\n"
    )
    print(json.dumps({k: v for k, v in payload.items() if k not in ("history", "bundle_history")}, sort_keys=True), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prices", type=Path, default=Path("results/practice_global_interval_prices.npz"))
    parser.add_argument("--out", type=Path, default=Path("results/projected_price_search"))
    parser.add_argument("--theta", type=int, default=140)
    parser.add_argument("--iterations", type=int, default=100)
    parser.add_argument("--bundle-iterations", type=int, default=0)
    parser.add_argument("--bundle-radii", default="2,5,10,20,50")
    parser.add_argument("--bundle-prox", type=float, default=0.5)
    parser.add_argument("--seconds", type=float, default=1200)
    parser.add_argument("--lower-bound-cents", type=int, default=2111949)
    parser.add_argument("--theta-scan-every", type=int, default=10)
    parser.add_argument("--stagnation-limit", type=int, default=8)
    parser.add_argument("--verbose", action="store_true")
    run(parser.parse_args())


if __name__ == "__main__":
    main()
