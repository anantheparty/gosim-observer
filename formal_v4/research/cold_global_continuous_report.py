#!/usr/bin/env python3
"""Attribute consecutive best-plan increases to their producing LNS operator.

This accounting does not replace controlled operator ablations: an improvement
can depend on preceding changes generated by another operator.
"""
import csv,json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"results/cold_global_search_20261003"


def max_factors(path):
    factors={}
    for r in csv.DictReader((path/"observations.csv").open()):
        if r["valid"]=="true":factors[r["target_id"]]=max(factors.get(r["target_id"],0),float(r["factor"]))
    return factors


def report(card):
    folder=OUT/f"continuous_{card}";summary=json.loads((folder/"summary.json").read_text());history=json.loads((folder/"history.json").read_text());previous=summary["baseline_model"]
    stats={str(w):{"best_improvements":0,"total_delta":0.,"science_delta":0.,"required_penalty_delta":0.,"request_reward_delta":0.,"uniformity_delta":0.} for w in (1,2,4)}
    for row in history:
        st=stats[str(row["operator_nights"])];st["best_improvements"]+=1
        st["total_delta"]+=row["total"]-previous["total"];st["science_delta"]+=row["science"]-previous["science"]
        st["required_penalty_delta"]+=50*(previous["required_missing"]-row["required_missing"])
        st["request_reward_delta"]+=row["request_reward"]-previous["request_reward"];st["uniformity_delta"]+=previous["uniformity_penalty"]-row["uniformity_penalty"];previous=row
    source=Path(summary["source"]);old=max_factors(source);new=max_factors(folder/"optimized_native")
    targets={r["target_id"]:r for r in csv.DictReader((ROOT/"upstream/gosim-observer-examples/local-cards"/card/"public/targets.csv").open())}
    rescued=[{**targets[k],"old_factor":old.get(k,0),"new_factor":new[k]} for k in targets if targets[k]["required"]=="true" and old.get(k,0)<.5<=new.get(k,0)]
    result={"card":card,"source":str(source),"source_total":summary["incumbent_gate"]["expected_total"],"native_total":summary["native"]["total"],"native_delta":summary["official_replay_total_delta"],"native_model_abs_error":summary["native_model_abs_error"],"baseline":summary["baseline_model"],"optimized":summary["optimized_model"],"operator_accounting":stats,"operator_note":"Credit for consecutive incumbent increases; not an independent causal ablation.","rescued_required":rescued,"limitation":"Public local truth oracle; original report times fixed; finite column pool; no online policy gain or global certificate."}
    (folder/"report.json").write_text(json.dumps(result,indent=2));return result


def main():
    results={card:report(card) for card in ("L1","L2") if (OUT/f"continuous_{card}/summary.json").exists()}
    (OUT/"continuous_summary.json").write_text(json.dumps(results,indent=2))
    print(json.dumps(results,indent=2))


if __name__=="__main__":main()
