"""Public-input candidate critic; exact public geometry stays in SpatialPlanner.

The critic changes only selection among complete physical candidates generated by
one deterministic source. Training labels are fixed-continuation full-season
interventions, never inference inputs. No card name, target id, truth or LLM is a
model feature. The baseline uses the identical exhaustive bounded candidate pool.
"""
from pathlib import Path
import time
import numpy as np
from research.spatial_candidates import SpatialPlanner, parse_utc, local_sidereal

FEATURES = [
    "duration_fraction", "log_duration", "baseline_candidate_rate", "assignment_fraction",
    "predicted_science_gain", "required_rescues", "request_progress_value", "uniformity_gain",
    "mean_log_flux", "min_log_flux", "max_log_flux", "mean_current_score_fraction",
    "new_target_fraction", "mean_current_factor_lower", "mean_predicted_factor", "saturated_fraction",
    "required_fraction", "mean_nights_remaining", "min_nights_remaining", "mean_hour_angle_fraction",
    "max_hour_angle_fraction", "mean_altitude", "min_altitude", "mean_public_quality_rate",
    "global_required_missing_fraction", "global_unfinished_fraction", "season_time_remaining_fraction",
    "quality_scale", "band_quality_scale", "program_dark", "program_bright", "program_backup",
    "best_pool_rate", "relative_pool_rate", "baseline_duration_fraction",
]


class CandidateCriticPlanner(SpatialPlanner):
    def __init__(self, initial_payload):
        super().__init__(initial_payload)
        self.model = None
        self.mode = "baseline"
        self.candidates = []
        self.critic_calls = self.critic_changes = 0
        self.critic_seconds = 0.
        self.critic_margin = 0.

    def load_model(self, path):
        self.model = dict(np.load(Path(path)))
        self.mode = "critic"

    def predict(self, x):
        m = self.model
        a = (np.asarray(x, np.float32) - m["xmean"]) / m["xscale"]
        a = np.maximum(0., np.einsum("ij,jk->ik",a,m["w1"],optimize=False) + m["b1"])
        out = (np.einsum("ij,j->i",a,m["w2"].reshape(-1),optimize=False) + m["b2"]).reshape(-1) * float(m["yscale"]) + float(m["ymean"])
        if not np.isfinite(out).all():
            raise ValueError("nonfinite candidate critic output")
        return out

    def _features(self, c, args):
        _, center, duration, program, idx, fibers = c
        (pool, vectors, up, k, scores, factors, multiplier, req_missing, request_reward,
         request_threshold, request_deadline, uniform_bonus, urgency, seconds_left, safety, focus_request) = args
        raw = np.minimum(1., k[idx] * duration)
        robust = np.minimum(1., raw / safety)
        science = np.maximum(0., self.weight[idx] * raw * multiplier[program, idx] - scores[idx])
        rd = req_missing[idx] & (robust + 1e-10 >= self.req_threshold)
        rq = (request_reward[idx] > 0) & (robust + 1e-10 >= request_threshold[idx]) & (duration <= request_deadline[idx])
        ud = (factors[idx] < self.uniform_threshold) & (robust + 1e-10 >= self.uniform_threshold)
        left = np.maximum(1, self.future_nights[self._critic_night, idx])
        hh = self._critic_hour[idx] / np.maximum(self.hmax[idx], 1.)
        alt = self._critic_alt[idx]
        total_time = sum((b-a).total_seconds() for a,b in self.nights)
        remain_time = sum(max(0., (b-max(a,self._critic_now)).total_seconds()) for a,b in self.nights)
        value = [duration/self.tmax, np.log1p(duration)/np.log1p(self.tmax), float(c[0])*100,
                 len(idx)/self.nfib, science.sum()/20, rd.sum()/self.nfib,
                 (rq*request_reward[idx]).sum()/200, (ud*uniform_bonus[idx]).sum()/20,
                 np.log1p(self.flux[idx]).mean(), np.log1p(self.flux[idx]).min(), np.log1p(self.flux[idx]).max(),
                 np.mean(scores[idx]/np.maximum(self.weight[idx]*1.2,1e-9)), np.mean(scores[idx]<1e-8),
                 factors[idx].mean(), raw.mean(), np.mean(raw>=.999), self.required[idx].mean(),
                 left.mean()/len(self.nights), left.min()/len(self.nights), hh.mean(), hh.max(),
                 alt.mean()/90, alt.min()/90, np.mean(k[idx]*self.f0t0/np.maximum(self.flux[idx],1e-9)),
                 req_missing.sum()/max(1,self.required.sum()), np.mean(factors<.5), remain_time/max(total_time,1),
                 self._critic_env.get("quality_scale",.55), self._critic_env.get("program_band_quality_scale",.6),
                 float(program==0), float(program==1), float(program==2)]
        return np.asarray(value, np.float32)

    def _evaluate(self, center, pool, vectors, up, k, scores, factors, multiplier, req_missing,
                  request_reward, request_threshold, request_deadline, uniform_bonus, urgency,
                  seconds_left, safety, focus_request=None):
        args = (pool,vectors,up,k,scores,factors,multiplier,req_missing,request_reward,request_threshold,
                request_deadline,uniform_bonus,urgency,seconds_left,safety,focus_request)
        self._critic_eval_args = args
        c = super()._evaluate(center, *args)
        if c is not None:
            self.candidates.append((c, self._features(c, args)))
        return c

    def candidate_action(self, c):
        _, center, duration, program, chosen, fibers = c
        ea = float(self._critic_env.get("pointing_offset_alt_deg",0))
        ez = float(self._critic_env.get("pointing_offset_az_deg",0))
        return {"action":"observe", "pointing":{"alt_deg":round(center[0]-ea,7),"az_deg":round((center[1]-ez)%360,7)},
                "assignments":{str(int(f)):self.ids[int(i)] for i,f in zip(chosen,fibers)},
                "duration_seconds":int(duration), "program":("DARK","BRIGHT","BACKUP")[program]}

    def choose(self, snapshot, best_scores, best_factors, env_estimate=None, active_requests=None):
        self.candidates = []
        self._critic_now = parse_utc(snapshot["now_utc"])
        self._critic_night = next((i for i,(a,b) in enumerate(self.nights) if a<=self._critic_now<b),0)
        self._critic_alt,_,self._critic_hour,_ = self._altaz(local_sidereal(self._critic_now,self.lon))
        self._critic_env = dict(env_estimate or {})
        # Fixed work removes candidate-order changes from timing noise.
        self._critic_env["planning_budget_seconds"] = 30.
        self._critic_env["anchor_count"] = 24
        baseline = super().choose(snapshot,best_scores,best_factors,self._critic_env,active_requests)
        if baseline is None or not self.candidates:
            self.feature_matrix = np.zeros((0,len(FEATURES)),np.float32)
            return baseline
        # Deduplicate physical actions; use the same bounded top pool for train/deploy.
        unique = {}
        import json
        for c,x in self.candidates:
            a = self.candidate_action(c)
            unique.setdefault(json.dumps(a,sort_keys=True), (c,x,a))
        pool = sorted(unique.values(),key=lambda z:z[0][0],reverse=True)[:32]
        self.candidates = pool
        best_rate = pool[0][0][0]
        base_duration = pool[0][0][2]
        self.feature_matrix = np.stack([np.r_[x,best_rate*100,c[0]/max(best_rate,1e-12),base_duration/self.tmax]
                                        for c,x,a in pool]).astype(np.float32)
        self.baseline_index = next((i for i,z in enumerate(pool) if z[2]==baseline),None)
        if self.baseline_index is None:
            raise RuntimeError("exact baseline action missing from deterministic candidate pool")
        if self.mode != "critic" or self.model is None:
            return baseline
        start=time.perf_counter()
        pred = self.predict(self.feature_matrix)
        best = int(np.argmax(pred))
        self.critic_calls+=1
        self.critic_seconds+=time.perf_counter()-start
        if pred[best] - pred[self.baseline_index] <= self.critic_margin:
            return baseline
        c,_,action = pool[best]
        self.critic_changes += int(action!=baseline)
        # Recompute feedback metadata for the chosen candidate, from the public
        # model rather than reusing another field's feedback prediction.
        _,_,duration,program,idx,fibers=c
        alt,az,_,_=self._altaz(local_sidereal(self._critic_now,self.lon))
        self.last_prediction={self.ids[int(i)]:{"index":int(i),"fiber_id":int(f),"alt_deg":float(alt[i]),"az_deg":float(az[i])}
                              for i,f in zip(idx,fibers)}
        return action
